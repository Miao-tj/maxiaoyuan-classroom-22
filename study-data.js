export function installStudyContent(course){
  const existing=new Map(course.chapters.map(c=>[c.id,c]));
  const oldModules={'demo-practice':'认识论','demo-contradiction':'辩证法','demo-specific-analysis':'辩证法'};
  for(const chapter of course.chapters) chapter.module ||= oldModules[chapter.id] || '';
  materials.forEach(([key,title,body],index)=>{
    const id='study-'+key,module=studyModules[index][0];
    if(existing.has(id))return;
    const snippet=id+'-read',concept=id+'-concept';
    course.chapters.push({id,module,title,summary:studyModules[index][2],paragraphs:[{id:snippet,title,text:body}],concepts:[{id:concept,label:title,definition:body}],guidingQuestion:'如何用生活中的例子解释'+title+'？',referenceIds:[],questions:items[index].map(([type,prompt,options,keys,explanation],n)=>{
      const qid=id+'-'+(n+1), opts=options.map((text,i)=>({id:qid+'-'+i,label:String.fromCharCode(65+i),text}));
      return {id:qid,type,label:'课程练习',prompt,options:opts,answerKeys:keys.map(i=>opts[i].id),explanation,snippetIds:[snippet],conceptIds:[concept]};
    })});
  });
  return course;
}

